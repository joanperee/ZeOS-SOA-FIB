/*
 *  colors.h - Colors per la pantalla. Cada caràcter son
 *  dos Bytes. El primer conté el codi ASCII i el segon el 
 *  color, que es divideix en fons (4 bits de més pes) i 
 *  color del text (4 bits de menys pes).
 */

#ifndef COLORS_H
#define COLORS_H

#define BLACK   0x0
#define BLUE    0x1
#define GREEN   0x2
#define CYAN    0x3
#define RED     0x4
#define MAGENTA 0x5
#define BROWN   0x6
#define WHITE   0x7

#endif /* COLORS_H */